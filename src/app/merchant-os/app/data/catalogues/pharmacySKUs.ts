// Helper functions
export function getSKUsBySchedule(schedule: 0 | 1 | 2 | 3 | 4 | 5 | 6): PharmacySKU[] {
  return allPharmacySKUs.filter(sku => sku.scheduleClass === schedule)
}

export function getSKUsByCategory(category: PharmacyCategory): PharmacySKU[] {
  return allPharmacySKUs.filter(sku => sku.category === category)
}

export function getSKUsForSubVertical(subVertical: keyof typeof pharmacySubVerticals): PharmacySKU[] {
  const config = pharmacySubVerticals[subVertical]
  if (!config) return []
  
  return allPharmacySKUs.filter(sku => 
    config.scheduleAccess.includes(sku.scheduleClass) &&
    config.categories.includes(sku.category)
  )
}

export function validateNAPPI(code: string): boolean {
  return /^\d{7,9}(-\d{3})?$/.test(code)
}

export function getControlledSubstanceCount(): number {
  return allPharmacySKUs.filter(sku => sku.controlledSubstance).length
}

export function getColdChainCount(): number {
  return allPharmacySKUs.filter(sku => sku.coldChain).length
}

