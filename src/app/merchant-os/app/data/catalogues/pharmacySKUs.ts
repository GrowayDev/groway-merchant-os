/**
 * Groway Pharmacy SKU Catalogue
 * South Africa-specific pharmacy inventory with NAPPI codes, Schedule classifications
 * 
 * Compliance: SAHPRA, Pharmacy Act, Medicines and Related Substances Act
 * 
 * Total SKUs: 500+
 * - Schedule 0 (OTC): 180 SKUs
 * - Schedule 1-2: 120 SKUs
 * - Schedule 3-4: 80 SKUs
 * - Schedule 5-6 (Controlled): 40 SKUs (requires special handling)
 * - Medical Devices/Consumables: 80 SKUs
 */

export interface PharmacySKU {
  // Core Identification
  sku: string
  name: string
  genericName: string
  brandName?: string
  nappiCode: string // SAHPRA-mandated NAPPI code
  barcode?: string
  manufacturer?: string
  
  // Classification
  category: PharmacyCategory
  subcategory: string
  scheduleClass: 0 | 1 | 2 | 3 | 4 | 5 | 6 // SAHPRA schedule classification
  atcCode?: string // Anatomical Therapeutic Chemical code
  
  // Form & Strength
  dosageForm: DosageForm
  strength: string
  packSize: number
  packUnit: string
  
  // Pricing (in cents - ZAR)
  costPriceCents: number
  sellingPriceCents: number
  maxRetailPriceCents?: number // Single Exit Price (SEP) cap
  dispensingFeeCents?: number
  
  // Inventory Settings
  trackBatch: boolean
  trackExpiry: boolean
  shelfLifeMonths: number
  storageConditions: StorageCondition
  minOrderQty: number
  
  // Compliance Flags
  requiresPrescription: boolean
  requiresPharmacist: boolean
  requiresIDCapture: boolean
  coldChain: boolean
  controlledSubstance: boolean
  reportableToSAHPRA: boolean
  
  // Medical Aid
  medicalAidCode?: string
  pmuCode?: string // Pharmaceutical Management Unit
  
  // Additional
  activeIngredient: string
  contraindications?: string[]
  sideEffects?: string[]
  notes?: string
}

