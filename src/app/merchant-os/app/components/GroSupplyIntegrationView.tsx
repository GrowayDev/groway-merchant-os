interface Supplier {
  id: string
  name: string
  tier: 'bronze' | 'silver' | 'gold' | 'preferred'
  status: 'connected' | 'pending' | 'disconnected'
  rating: number
  leadTime: number // days
  categories: string[]
  lastSync?: string
  catalogUpdates: number
  priceChanges: number
  newProducts: number
  paymentTerms: string
  autoRFQEnabled: boolean
}

interface LowStockItem {
  id: string
  sku: string
  name: string
  currentStock: number
  reorderPoint: number
  reorderQty: number
  category: string
  preferredSupplier?: string
  preferredSupplierId?: string
  autoRFQEnabled: boolean
  unitCost: number
  estimatedCost: number
  daysUntilStockout: number
  urgency: 'critical' | 'high' | 'medium'
}

interface AutoRFQRule {
  id: string
  name: string
  categoryId: string
  categoryName: string
  enabled: boolean
  triggerType: 'reorder_point' | 'days_of_stock' | 'manual'
  triggerValue: number
  preferredSupplierId?: string
  preferredSupplierName?: string
  defaultQty: number
  leadTimeBuffer: number
  autoSend: boolean
  autoAwardThreshold?: number
}

interface RFQ {
  id: string
  number: string
  status: 'draft' | 'sent' | 'quoted' | 'awarded' | 'cancelled'
  createdAt: string
  requiredBy: string
  supplierId?: string
  supplierName?: string
  items: {
    sku: string
    description: string
    quantity: number
    unit: string
    unitPrice?: number
  }[]
  quotes?: Quote[]
  total?: number
  isAutoGenerated: boolean
}

interface Quote {
  id: string
  supplierId: string
  supplierName: string
  supplierTier: string
  total: number
  deliveryDays: number
  validUntil: string
  items: {
    sku: string
    unitPrice: number
    inStock: boolean
  }[]
}

interface ThreeWayMatch {
  id: string
  poId: string
  poNumber: string
  status: 'matched' | 'partial' | 'mismatch' | 'pending'
  supplier: string
  orderDate: string
  items: MatchItem[]
  overallMatch: number
  variances: Variance[]
  requiresApproval: boolean
  approvedBy?: string
  approvedAt?: string
}

interface MatchItem {
  sku: string
  description: string
  // Purchase Order
  poQuantity: number
  poUnitPrice: number
  poTotal: number
  // Quote
  quotedQuantity: number
  quotedUnitPrice: number
  quotedTotal: number
  // GRN (Goods Received Note)
  receivedQuantity: number
  rejectedQuantity: number
  receivedTotal: number
  // Match Status
  quantityMatch: 'match' | 'within_tolerance' | 'mismatch'
  priceMatch: 'match' | 'within_tolerance' | 'mismatch'
  quantityVariance: number
  priceVariance: number
}

interface Variance {
  type: 'quantity' | 'price' | 'product'
  sku: string
  description: string
  expected: number | string
  actual: number | string
  variance: number | string
  percentage: number
  requiresAction: boolean
}

interface GroCreditFacility {
  availableCredit: number
  creditLimit: number
  usedCredit: number
  utilizationPercent: number
  creditScore: number
  rating: 'excellent' | 'good' | 'fair' | 'poor'
  nextPaymentDue: string
  nextPaymentAmount: number
  paymentStatus: 'current' | 'due_soon' | 'overdue'
  interestRate: number
}

