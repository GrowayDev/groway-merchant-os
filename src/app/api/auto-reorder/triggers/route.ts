import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'

// GET /api/auto-reorder/triggers - Get trigger status and pending actions
export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url)
    const merchantId = searchParams.get('merchantId')
    const includePending = searchParams.get('includePending') === 'true'

    // Get all configs with auto-RFQ enabled
    const configs = await db.autoReorderConfig.findMany({
      where: {
        merchantId: merchantId || 'default',
        enabled: true,
        autoRfqEnabled: true
      }
    })

    // Get pending alerts
    const pendingAlerts = await db.stockAlert.findMany({
      where: {
        merchantId: merchantId || 'default',
        status: 'active',
        alertType: { in: ['low_stock', 'out_of_stock', 'reorder'] }
      },
      orderBy: [
        { severity: 'desc' },
        { triggeredAt: 'desc' }
      ]
    })

    // Get recent RFQs generated by auto-reorder
    const recentRfqs = await db.rFQ.findMany({
      where: {
        notes: { contains: 'Auto-generated' },
        createdAt: {
          gte: new Date(Date.now() - 7 * 24 * 60 * 60 * 1000) // Last 7 days
        }
      },
      orderBy: { createdAt: 'desc' },
      take: 10
    })

    // Calculate trigger stats
    const triggerStats = {
      configsEnabled: configs.length,
      pendingAlerts: pendingAlerts.length,
      criticalAlerts: pendingAlerts.filter(a => a.severity === 'critical').length,
      recentRfqs: recentRfqs.length,
      nextScheduledCheck: new Date(Date.now() + 60 * 60 * 1000).toISOString() // 1 hour from now
    }

    // Get products needing reorder (mock - in real implementation, would check actual stock)
    const productsNeedingReorder = await getProductsNeedingReorder(merchantId)

    return NextResponse.json({
      triggerStats,
      pendingAlerts,
      recentRfqs,
      productsNeedingReorder,
      configs: includePending ? configs : undefined
    })
  } catch (error) {
    console.error('Error fetching trigger status:', error)
    return NextResponse.json(
      { error: 'Failed to fetch trigger status' },
      { status: 500 }
    )
  }
}

// POST /api/auto-reorder/triggers - Trigger stock check and generate alerts/RFQs
export async function POST(request: NextRequest) {
  try {
    const body = await request.json()
    const { merchantId, action = 'check' } = body

    if (action === 'check') {
      // Perform stock check and generate alerts
      const alerts = await performStockCheck(merchantId)
      
      return NextResponse.json({
        success: true,
        action: 'stock_check',
        alertsGenerated: alerts.length,
        alerts: alerts.slice(0, 20)
      })
    }

    if (action === 'generate_rfqs') {
      // Generate RFQs for products below reorder point
      const rfqs = await generateAutoRfqs(merchantId)
      
      return NextResponse.json({
        success: true,
        action: 'generate_rfqs',
        rfqsGenerated: rfqs.length,
        rfqs
      })
    }

    if (action === 'acknowledge_alert') {
      const { alertId, acknowledgedBy } = body
      
      if (!alertId) {
        return NextResponse.json(
          { error: 'alertId is required for acknowledge action' },
          { status: 400 }
        )
      }

      const alert = await db.stockAlert.update({
        where: { id: alertId },
        data: {
          status: 'acknowledged',
          acknowledgedBy,
          acknowledgedAt: new Date()
        }
      })

      return NextResponse.json({
        success: true,
        action: 'acknowledge_alert',
        alert
      })
    }

    if (action === 'resolve_alert') {
      const { alertId, resolvedBy, resolution } = body
      
      if (!alertId) {
        return NextResponse.json(
          { error: 'alertId is required for resolve action' },
          { status: 400 }
        )
      }

      const alert = await db.stockAlert.update({
        where: { id: alertId },
        data: {
          status: 'resolved',
          resolvedBy,
          resolvedAt: new Date(),
          resolution
        }
      })

      return NextResponse.json({
        success: true,
        action: 'resolve_alert',
        alert
      })
    }

    return NextResponse.json(
      { error: 'Invalid action. Use: check, generate_rfqs, acknowledge_alert, or resolve_alert' },
      { status: 400 }
    )
  } catch (error) {
    console.error('Error processing trigger action:', error)
    return NextResponse.json(
      { error: 'Failed to process trigger action' },
      { status: 500 }
    )
  }
}

// Helper function to perform stock check
async function performStockCheck(merchantId: string | null) {
  // Get all auto-reorder configs
  const configs = await db.autoReorderConfig.findMany({
    where: {
      merchantId: merchantId || 'default',
      enabled: true
    }
  })

  const alerts = []

  for (const config of configs) {
    // Get current stock (mock - in real implementation, would query Product/StockMovement)
    const currentStock = Math.floor(Math.random() * config.reorderPoint * 2)
    
    // Check if stock is at or below reorder point
    if (currentStock <= config.reorderPoint) {
      const severity = currentStock <= config.safetyStock ? 'critical' : 'warning'
      const alertType = currentStock <= 0 ? 'out_of_stock' : 
                       currentStock <= config.safetyStock ? 'low_stock' : 'reorder'

      // Check if alert already exists
      const existingAlert = await db.stockAlert.findFirst({
        where: {
          merchantId: merchantId || 'default',
          sku: config.sku,
          alertType,
          status: 'active'
        }
      })

      if (!existingAlert) {
        // Create new alert
        const alert = await db.stockAlert.create({
          data: {
            id: `alert_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
            merchantId: merchantId || 'default',
            sku: config.sku,
            productName: config.productName,
            alertType,
            severity,
            status: 'active',
            currentStock,
            threshold: config.reorderPoint,
            variance: ((config.reorderPoint - currentStock) / config.reorderPoint) * 100,
            suggestedAction: alertType === 'out_of_stock' 
              ? 'Immediate reorder required' 
              : 'Initiate reorder process',
            suggestedQty: config.reorderQty,
            supplierId: config.preferredSupplierId || undefined,
            leadTime: 7
          }
        })
        alerts.push(alert)
      }
    }
  }

  return alerts
}

// Helper function to generate auto RFQs
async function generateAutoRfqs(merchantId: string | null) {
  // Get pending low_stock and reorder alerts
  const alerts = await db.stockAlert.findMany({
    where: {
      merchantId: merchantId || 'default',
      alertType: { in: ['low_stock', 'reorder'] },
      status: 'active'
    }
  })

  const rfqs = []

  // Group alerts by supplier
  const alertsBySupplier = alerts.reduce((acc, alert) => {
    const supplierId = alert.supplierId || 'unknown'
    if (!acc[supplierId]) acc[supplierId] = []
    acc[supplierId].push(alert)
    return acc
  }, {} as Record<string, typeof alerts>)

  for (const [supplierId, supplierAlerts] of Object.entries(alertsBySupplier)) {
    // Create RFQ
    const rfqNumber = `RFQ-${Date.now().toString(36).toUpperCase()}`
    
    const rfq = await db.rFQ.create({
      data: {
        id: `rfq_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
        number: rfqNumber,
        supplierId: supplierId !== 'unknown' ? supplierId : null,
        status: 'draft',
        requiredBy: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString().split('T')[0], // 7 days from now
        notes: 'Auto-generated from low stock alert'
      }
    })

    // Create RFQ items
    for (const alert of supplierAlerts) {
      await db.rFQItem.create({
        data: {
          id: `rfq_item_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
          rfqId: rfq.id,
          sku: alert.sku,
          description: alert.productName,
          quantity: alert.suggestedQty || 1,
          unit: 'units'
        }
      })
    }

    // Update alert with RFQ reference
    for (const alert of supplierAlerts) {
      await db.stockAlert.update({
        where: { id: alert.id },
        data: {
          suggestedAction: `RFQ ${rfqNumber} generated - awaiting quotes`
        }
      })
    }

    rfqs.push(rfq)
  }

  return rfqs
}

// Helper function to get products needing reorder
async function getProductsNeedingReorder(merchantId: string | null) {
  // Get configs with stock below reorder point
  const configs = await db.autoReorderConfig.findMany({
    where: {
      merchantId: merchantId || 'default',
      enabled: true
    },
    take: 20
  })

  // Mock current stock calculation
  return configs.map(config => {
    const currentStock = Math.floor(Math.random() * config.reorderPoint * 1.5)
    const needsReorder = currentStock <= config.reorderPoint
    
    return {
      sku: config.sku,
      productName: config.productName,
      currentStock,
      reorderPoint: config.reorderPoint,
      safetyStock: config.safetyStock,
      suggestedOrderQty: config.reorderQty,
      preferredSupplierId: config.preferredSupplierId,
      needsReorder,
      urgency: currentStock <= config.safetyStock ? 'critical' : 
              currentStock <= config.reorderPoint ? 'high' : 'normal',
      lastReorderAt: config.lastReorderAt
    }
  }).filter(p => p.needsReorder)
}
