// POST /api/merchant-os/grosupply/auto-rfq - Trigger auto-RFQ
export async function POST(request: NextRequest) {
  try {
    const body = await request.json()

    // Validate required fields
    if (!body.items || body.items.length === 0) {
      return NextResponse.json({ error: 'Items are required' }, { status: 400 })
    }

    const number = body.number || generateRFQNumber()

    // Calculate required delivery date based on lead time + buffer
    const leadTimeBuffer = body.leadTimeBuffer || 3
    const requiredBy = body.requiredBy || new Date(Date.now() + (leadTimeBuffer * 24 * 60 * 60 * 1000)).toISOString().split('T')[0]

    // In production, create RFQ in database
    const rfq = {
      id: `rfq-${Date.now()}`,
      number,
      status: body.autoSend ? 'sent' : 'draft',
      createdAt: new Date().toISOString(),
      requiredBy,
      supplierId: body.supplierId,
      supplierName: body.supplierName,
      items: body.items.map((item: { sku: string; description: string; quantity: number; unit?: string }) => ({
        sku: item.sku,
        description: item.description,
        quantity: item.quantity,
        unit: item.unit || 'units',
      })),
      isAutoGenerated: true,
    }

    // In production, send notification to supplier via email/API
    if (body.autoSend) {
      console.log(`Auto-RFQ ${number} sent to supplier ${body.supplierName}`)
    }

    return NextResponse.json({ 
      message: body.autoSend ? 'RFQ sent to supplier' : 'RFQ created as draft',
      rfq 
    }, { status: 201 })
  } catch (error) {
    console.error('Error creating auto-RFQ:', error)
    return NextResponse.json({ error: 'Failed to create auto-RFQ' }, { status: 500 })
  }
}

