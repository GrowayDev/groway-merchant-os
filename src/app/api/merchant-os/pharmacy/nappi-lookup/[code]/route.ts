// GET /api/merchant-os/pharmacy/nappi-lookup/[code] - Lookup NAPPI code
export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ code: string }> }
) {
  try {
    const { code } = await params
    const searchCode = code.toUpperCase()

    // Search by NAPPI code or product name
    const results = mockNAPPIProducts.filter(product => {
      const nappiMatch = product.nappiCode.toLowerCase().includes(searchCode.toLowerCase())
      const nameMatch = product.productName.toLowerCase().includes(searchCode.toLowerCase()) ||
                       product.genericName.toLowerCase().includes(searchCode.toLowerCase()) ||
                       (product.brandName && product.brandName.toLowerCase().includes(searchCode.toLowerCase()))
      return nappiMatch || nameMatch
    })

    // If exact NAPPI code match, return single product
    const exactMatch = mockNAPPIProducts.find(p => 
      p.nappiCode.toLowerCase() === searchCode.toLowerCase()
    )

    if (exactMatch) {
      return NextResponse.json({
        product: exactMatch,
        nappiCode: exactMatch.nappiCode,
        valid: true,
        message: 'NAPPI code validated',
      })
    }

    if (results.length > 0) {
      return NextResponse.json({
        products: results,
        total: results.length,
      })
    }

    // NAPPI code not found
    return NextResponse.json({
      products: [],
      total: 0,
      message: 'No products found matching the search criteria',
    })
  } catch (error) {
    console.error('Error looking up NAPPI code:', error)
    return NextResponse.json(
      { error: 'Failed to lookup NAPPI code' },
      { status: 500 }
    )
  }
}
