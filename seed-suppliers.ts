async function seedGroSupply() {
  console.log('🌱 Seeding GroSupply suppliers with vertical alignment...')
  console.log(`📊 Total suppliers to seed: ${suppliers.length}`)

  // Clear existing suppliers first
  const existingCount = await db.supplier.count()
  if (existingCount > 0) {
    console.log(`🗑️  Deleting ${existingCount} existing suppliers...`)
    await db.supplier.deleteMany({})
  }

  let created = 0
  let errors = 0

  for (const supplier of suppliers) {
    try {
      await db.supplier.create({
        data: {
          name: supplier.name,
          code: supplier.code,
          contactPerson: supplier.contactPerson,
          email: supplier.email,
          phone: supplier.phone,
          city: supplier.city,
          province: supplier.province,
          supplierType: supplier.supplierType as any,
          tier: supplier.tier as any,
          bbbeeLevel: supplier.bbbeeLevel,
          rating: 4.0 + Math.random() * 1.0, // Random rating between 4.0-5.0
          reviewCount: Math.floor(Math.random() * 200) + 10,
          deliveryDays: Math.floor(Math.random() * 5) + 1,
          minOrderValue: Math.floor(Math.random() * 1000) + 100,
          paymentTerms: ['cod', 'net7', 'net15', 'net30', 'net60'][Math.floor(Math.random() * 5)],
          categories: JSON.stringify(supplier.categories),
          verticals: JSON.stringify(supplier.verticals),
          subVerticals: JSON.stringify(supplier.subVerticals),
          fulfillmentRate: 90 + Math.random() * 10, // 90-100%
          status: 'active',
          verificationStatus: 'verified',
          verifiedAt: new Date(),
        },
      })
      created++
      console.log(`✅ Created: ${supplier.name} (${supplier.verticals.join(', ')})`)
    } catch (error: any) {
      errors++
      console.error(`❌ Error creating ${supplier.name}:`, error.message)
    }
  }

  // Summary by vertical
  console.log('\n📈 Supplier count by vertical:')
  const verticalCounts: Record<string, number> = {}
  for (const supplier of suppliers) {
    for (const v of supplier.verticals) {
      verticalCounts[v] = (verticalCounts[v] || 0) + 1
    }
  }
  for (const [vertical, count] of Object.entries(verticalCounts)) {
    console.log(`   ${vertical}: ${count} suppliers`)
  }

  console.log('\n🎉 GroSupply seeding complete!')
  console.log(`✅ Created: ${created}`)
  console.log(`❌ Errors: ${errors}`)
}

seedGroSupply()
  .catch((e) => {
    console.error('❌ Seeding failed:', e)
    process.exit(1)
  })
  .finally(async () => {
    await db.$disconnect()
  })
